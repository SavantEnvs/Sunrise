#!/usr/bin/env python3
"""Generate a dispatch-table fuzz harness over every byte-span decoder declared in some headers.

Authoring-time tool (not run by build.sh; its output is committed). Usage:
  gen_dispatch.py <src-root> <out.cpp> <exclude-regex|-> <header-dir-or-file>...
A decoder is a free function declared `[[nodiscard]] bool NAME(std::span<const std::byte> x, ...)`
with one of the shapes (span), (span, T&), (span, T&, size_t&), (span, size_t, T&). The harness's
first input byte picks the decoder, the rest is the span it decodes.
"""
import os, re, sys

root, out, excl = sys.argv[1], sys.argv[2], sys.argv[3]
excl_re = re.compile(excl) if excl != '-' else None
headers = []
for p in sys.argv[4:]:
    full = os.path.join(root, p)
    if os.path.isdir(full):
        for d, _, fs in os.walk(full):
            headers += [os.path.relpath(os.path.join(d, f), root) for f in sorted(fs) if f.endswith('.h')]
    else:
        headers.append(p)
headers.sort()
ent = []


def namespace_at(text, pos):
    """The fully qualified namespace open at `pos`, tracking braces."""
    stack, i = [], 0
    ns_re = re.compile(r'namespace\s+([\w:]+)\s*\{')
    while i < pos:
        m = ns_re.match(text, i)
        if m and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == '_')):
            stack.append(m.group(1)); i = m.end(); continue
        c = text[i]
        if c == '{': stack.append(None)
        elif c == '}' and stack: stack.pop()
        i += 1
    names = [n for n in stack if n]
    return '::'.join(names) if names and None not in stack else ('::'.join(names) if names else '')


fn_re = re.compile(r'\[\[nodiscard\]\]\s+(?:inline\s+)?bool\s+(\w+)\s*\(([^)]*)\)\s*noexcept\s*;')
for h in headers:
    text = open(os.path.join(root, h)).read()
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    for m in fn_re.finditer(text):
        name, params = m.group(1), ' '.join(m.group(2).split())
        ps = [p.strip() for p in params.split(',')] if params else []
        shape = None
        if ps and re.match(r'(?:[\w:]*::)?(?:bits::)?Reader\s*&\s*\w+$', ps[0]) and 'bits' in ps[0] + text[:200] + ' bits':
            if len(ps) == 1: shape = 'RV'
            elif len(ps) == 2 and re.search(r'&\s*\w+$', ps[1]) and not ps[1].startswith('const'): shape = 'R'
            if shape:
                ns = namespace_at(text, m.start())
                if ns and not (excl_re and excl_re.search(ns + '::' + name)):
                    ent.append((h, ns + '::' + name, shape))
            continue
        if not ps or not re.match(r'std::span<const std::byte>\s+\w+$', ps[0]):
            continue
        if len(ps) == 1: shape = 'V'
        elif len(ps) == 2 and ps[1].endswith('&') or (len(ps) == 2 and re.search(r'&\s*\w+$', ps[1]) and not ps[1].startswith('const')): shape = 'O'
        elif len(ps) == 3 and re.search(r'&\s*\w+$', ps[1]) and not ps[1].startswith('const') and re.match(r'std::size_t\s*&\s*\w+$', ps[2]): shape = 'OC'
        elif len(ps) == 3 and re.match(r'std::size_t\s+\w+$', ps[1]) and re.search(r'&\s*\w+$', ps[2]) and not ps[2].startswith('const'): shape = 'BO'
        elif len(ps) == 3 and re.match(r'bool\s+\w+$', ps[1]) and re.search(r'&\s*\w+$', ps[2]) and not ps[2].startswith('const'): shape = 'SBO'
        if not shape:
            continue
        # namespace = the innermost `namespace X {` opened before the declaration
        ns = namespace_at(text, m.start())
        if not ns:
            continue
        q = ns + '::' + name
        if excl_re and excl_re.search(q):
            continue
        ent.append((h, q, shape))
# drop overloaded names (ambiguous address-of)
from collections import Counter
cnt = Counter(q for _, q, _ in ent)
ent = [e for e in ent if cnt[e[1]] == 1]
incs = sorted({h for h, _, _ in ent})
with open(out, 'w') as f:
    f.write('// GENERATED by mayhem/gen_dispatch.py from the public headers below; do not edit.\n')
    f.write('// First input byte picks one decoder, the rest of the input is the byte span it decodes.\n')
    f.write('#include "dispatch_common.h"\n')
    for h in incs: f.write(f'#include "{h}"\n')
    f.write('\nnamespace {\nusing namespace mayhem_dispatch;\nconst Entry kEntries[] = {\n')
    for h, q, s in ent:
        f.write(f'    {{"{q}", [](Bytes in) {{ return {"run_" + s.lower()}(&{q}, in); }}}},\n')
    f.write('};\n} // namespace\n\n')
    f.write('extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {\n'
            '    return mayhem_dispatch::dispatch(kEntries, sizeof(kEntries) / sizeof(kEntries[0]), data, size);\n}\n')
print(len(ent), 'decoders ->', out, file=sys.stderr)
